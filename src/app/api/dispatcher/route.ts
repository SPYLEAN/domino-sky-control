import { NextResponse } from "next/server";
import { z } from "zod";
import { sanitizeAiResponse } from "@/engine/ai-guard";
import { getNetwork } from "@/engine/data";
import { runRecovery, type Strategy } from "@/engine/recovery";
import { rulesExplanation } from "@/engine/rules-explainer";
import { validateScenario } from "@/engine/simulate";

export const runtime = "nodejs";

const Body = z.object({
  scenario: z.object({ airport: z.string(), start: z.number().int(), end: z.number().int() }),
  strategy: z.enum(["protect_passengers", "reduce_delay", "min_cancellations", "balanced"]),
});

export async function POST(req: Request) {
  const parsed = Body.safeParse(await req.json().catch(() => null));
  if (!parsed.success) return NextResponse.json({ error: "Invalid request" }, { status: 400 });
  const net = getNetwork();
  const problems = validateScenario(net, parsed.data.scenario);
  if (problems.length) return NextResponse.json({ error: problems.join(" ") }, { status: 400 });

  // The server recomputes everything; nothing numeric from the client or the model is trusted.
  const rep = runRecovery(net, parsed.data.scenario, parsed.data.strategy as Strategy);
  const fallback = { source: "rules" as const, ...rulesExplanation(rep) };
  const key = process.env.GEMINI_API_KEY;
  if (!key) return NextResponse.json({ ...fallback, note: "No AI key configured on the server — explanation generated by deterministic rules." });

  const top = rep.ranked.filter((c) => !c.sameOutcomeAs || c.actions.length === 0).slice(0, 5);
  const facts = top.map((c) => ({
    candidateId: c.id, title: c.title, summary: c.summary, rank: c.rank, improvesObjective: c.improves,
    delta: { cancelledPax: c.delta.cancelledPax, missedConnectionPax: c.delta.missedConnectionPax, paxDelayMinutes: c.delta.paxDelayMinutes, totalFlightDelay: c.delta.totalFlightDelay },
  }));
  const prompt = [
    "You are an airline operations dispatcher explaining a recovery decision to non-experts.",
    "Choose ONE candidateId from the list. The deterministic engine ranked them; prefer rank 1 unless you have a qualitative reason.",
    "STRICT RULES: Do not write any digits or numbers at all (the UI shows verified figures separately). Only mention flight ids, aircraft tails, crew ids or connection ids that appear in the facts. Do not invent resources or outcomes.",
    `Objective: ${rep.objective}`,
    `Facts (JSON): ${JSON.stringify(facts)}`,
  ].join("\n");
  try {
    const { GoogleGenAI, Type } = await import("@google/genai");
    const ai = new GoogleGenAI({ apiKey: key });
    const res = await ai.models.generateContent({
      model: process.env.GEMINI_MODEL ?? "gemini-2.5-flash",
      contents: prompt,
      config: {
        responseMimeType: "application/json",
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            recommendedCandidateId: { type: Type.STRING, enum: top.map((c) => c.id) },
            headline: { type: Type.STRING }, rationale: { type: Type.STRING },
            tradeoffs: { type: Type.ARRAY, items: { type: Type.STRING } },
          },
          required: ["recommendedCandidateId", "headline", "rationale", "tradeoffs"],
        },
      },
    });
    const guarded = sanitizeAiResponse(JSON.parse(res.text ?? "{}"), top.map((c) => c.id), net);
    if (!guarded.ok) return NextResponse.json({ ...fallback, note: `AI response rejected by the safety guard (${guarded.reason}) — showing deterministic explanation.` });
    return NextResponse.json({ source: "gemini", ...guarded.value });
  } catch {
    return NextResponse.json({ ...fallback, note: "AI service unavailable — showing deterministic explanation." });
  }
}
